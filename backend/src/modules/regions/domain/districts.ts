/**
 * Every Indian district with its state and agro-climatic region.
 * Built from the geoBoundaries 2021 district names (from the government's LGD
 * directory), cleaned to current official spellings, plus the districts created
 * since (each with its `parent`, the older district its land came from).
 * Spec: docs/superpowers/specs/2026-11-11-district-map-design.md §2.1, §2.5.
 *
 * Each entry is "Official name|alias|alias…", or "Name>Parent|alias…" for a
 * district formed after the 2021 boundaries. Aliases cover old names, the
 * boundary file's spellings and common city names gardeners type.
 */
import { RegionCluster } from '@prisma/client';

export interface District {
  name: string;
  state: string;
  region: RegionCluster;
  aliases: string[];
  /** The older district this one was carved from (no boundary of its own yet). */
  parent?: string;
  /** Only matched together with its state ("East, Delhi"), never alone. */
  needsState?: boolean;
  /** Resolvable from a location but never offered in the type-ahead. */
  selectable?: boolean;
}

