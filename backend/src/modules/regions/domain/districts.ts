/** Areas India counts as its own that have no district a gardener picks (spec §2.5.4). */
const NOT_SELECTABLE = new Set([
  'Pakistan-occupied Kashmir',
  'Gilgit-Baltistan and Aksai Chin',
]);

function parse(block: StateBlock, entry: string): District {
  const [head, ...aliases] = entry.split('|');
  const [name, parent] = head.split('>');
  return {
    name,
    state: block.state,
    region: block.overrides?.[name] ?? block.region,
    aliases,
    ...(parent ? { parent } : {}),
    ...(block.needsState?.includes(name) ? { needsState: true } : {}),
    ...(NOT_SELECTABLE.has(name) ? { selectable: false } : {}),
  };
}

export const DISTRICTS: readonly District[] = STATES.flatMap((block) =>
  block.districts.map((e) => parse(block, e)),
);

