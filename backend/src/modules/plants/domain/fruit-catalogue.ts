/**
 * The fruit trees people search for when adding a tree: one plain entry per
 * family plus popular varieties, with Hindi and regional names. The keys
 * (family, species, variety) of the first entries must not change: the boot-time
 * upsert matches on them, so a changed key would leave a duplicate row behind.
 * Polish item 3, phase 1: varieties for the 14 families the app already knows.
 */
export interface PlantSeed {
  species_family: string;
  species: string;
  variety?: string;
  display_name: string;
  plant_type: string;
  aliases: string[];
  languages?: Record<string, string[]>;
  regions?: string[];
  confidence_weight?: number;
}

type Region =
  | 'north_india'
  | 'east_india'
  | 'west_india'
  | 'central_india'
  | 'south_deccan'
  | 'coastal_humid'
  | 'hills_cool';

/** A named variety of a family: "Mango (Dasheri)". */
const variety = (
  family: string,
  species: string,
  label: string,
  name: string,
  aliases: string[],
  hi: string[],
  regions: Region[],
  confidence_weight = 0.9,
): PlantSeed => ({
  species_family: family,
  species,
  variety: name,
  display_name: `${label} (${name})`,
  plant_type: 'fruit_tree',
  aliases: [name.toLowerCase(), ...aliases],
  languages: { hi },
  regions,
  confidence_weight,
});

